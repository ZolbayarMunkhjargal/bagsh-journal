package app.kinderjournal.tools;

import app.kinderjournal.db.Repository;
import app.kinderjournal.model.Child;
import app.kinderjournal.model.Group;
import app.kinderjournal.report.ReportOptions;
import app.kinderjournal.report.ReportRenderer;
import app.kinderjournal.report.ReportType;
import app.kinderjournal.util.Dates;
import app.kinderjournal.util.Text;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.util.List;

/**
 * Writes every report type to HTML files without opening the window.
 *
 * <p>Used to check the printed output end to end, and useful on a real computer to
 * produce a whole term's paperwork as files that can then be printed in one go.
 */
public final class ReportExporter {

    private ReportExporter() {
    }

    /**
     * Generates one document per report type for the first class and child found.
     *
     * @return the number of files written
     */
    public static int exportAll(Path targetDir) throws IOException {
        Files.createDirectories(targetDir);
        int written = 0;
        try (Repository repo = Repository.open()) {
            ReportRenderer renderer = new ReportRenderer(repo);
            List<Group> groups = repo.groups().listActive();
            if (groups.isEmpty()) {
                System.out.println("  no classes to report on");
                return 0;
            }
            // Use the class with the most children so class-level documents have
            // something to show, and a child from it for the child-level ones.
            Group group = groups.get(0);
            for (Group candidate : groups) {
                if (candidate.getChildCount() > group.getChildCount()) {
                    group = candidate;
                }
            }
            List<Child> children = repo.children().listByGroup(group.getId(), false);
            Child child = children.isEmpty() ? null : children.get(0);
            LocalDate to = LocalDate.now();
            LocalDate from = to.minusMonths(3);

            for (ReportType type : ReportType.values()) {
                // Daily and weekly plans are only useful for days that actually have
                // activities, so those reports look at the current week.
                LocalDate rangeFrom = from;
                LocalDate rangeTo = to;
                if (type == ReportType.WEEKLY_PLAN) {
                    rangeFrom = Dates.startOfWeek(to);
                    rangeTo = rangeFrom.plusDays(6);
                } else if (type == ReportType.DAILY_PLAN) {
                    rangeFrom = Dates.startOfWeek(to);
                    rangeTo = rangeFrom;
                }

                ReportOptions options = ReportOptions.builder(type)
                        .group(group.getId())
                        // Only child-level documents are given a child, so a class
                        // report never carries one child's name in its header.
                        .child(type.needsChild() && child != null ? child.getId() : 0)
                        .range(rangeFrom, rangeTo)
                        .observations(true)
                        .interviews(true)
                        .plans(true)
                        .photos(true)
                        .confidential(true)
                        .teacher("Test run")
                        .notes("Generated by --export-reports on "
                                + Dates.display(Dates.toIso(to)) + ".")
                        .build();
                ReportRenderer.Rendered rendered;
                try {
                    rendered = renderer.render(options);
                } catch (RuntimeException ex) {
                    System.out.println("  FAILED " + type.label() + ": " + ex.getMessage());
                    continue;
                }
                String name = type.name().toLowerCase().replace('_', '-') + ".html";
                Path file = targetDir.resolve(name);
                Files.writeString(file, rendered.html());
                written++;
                System.out.printf("  %-26s %6d bytes  %s  [%s]%n", type.label(),
                        Files.size(file), file.getFileName(),
                        Text.summarise(subject(options, group, child), 44));
            }
        }
        return written;
    }

    /** What each document is about, printed alongside it for a quick sanity check. */
    private static String subject(ReportOptions options, Group group, Child child) {
        if (options.type().needsChild() && child != null) {
            return child.fullName() + " \u00b7 " + group.getName();
        }
        return group.getName();
    }
}

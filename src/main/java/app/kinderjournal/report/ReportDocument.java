package app.kinderjournal.report;

import java.util.List;

/**
 * A printed report, taken apart into the pieces the Office writers need.
 *
 * <p>The report renderer produces HTML, because that is what the preview pane and
 * the browser's print-to-PDF need. Word and Excel do not understand HTML, so
 * rather than write each report a second and third time, the HTML is parsed back
 * into this small set of blocks and both writers turn that into their format.
 * Every report type therefore gains Word and Excel support at once, and a change
 * to a report layout shows up in all three outputs.
 *
 * <p>The markup is generated by this program, so the parser only has to cope with
 * the tags that renderer emits - it is not a general HTML parser and does not try
 * to be.
 */
public final class ReportDocument {

    /** One span of text, so that bold can survive the trip through HTML. */
    public record Run(String text, boolean bold) {

        public Run(String text) {
            this(text, false);
        }
    }

    /** A heading, paragraph, table or list from the document body. */
    public sealed interface Block permits Heading, Paragraph, Bullets, Table {
    }

    public record Heading(int level, String text) implements Block {
    }

    /** A paragraph, with the runs that make up its text. */
    public record Paragraph(List<Run> runs) implements Block {

        public String text() {
            StringBuilder sb = new StringBuilder();
            for (Run run : runs) {
                sb.append(run.text());
            }
            return sb.toString();
        }

        public boolean isBlank() {
            return text().isBlank();
        }
    }

    public record Bullets(List<String> items) implements Block {
    }

    /**
     * A table.
     *
     * @param header the heading row, empty if the table had none
     * @param rows   the body rows
     */
    public record Table(List<String> header, List<List<String>> rows) implements Block {

        public int columnCount() {
            int columns = header.size();
            for (List<String> row : rows) {
                columns = Math.max(columns, row.size());
            }
            return columns;
        }
    }

    private final String title;
    private final String subtitle;
    private final List<Block> blocks;

    public ReportDocument(String title, String subtitle, List<Block> blocks) {
        this.title = title == null ? "" : title;
        this.subtitle = subtitle == null ? "" : subtitle;
        this.blocks = List.copyOf(blocks);
    }

    /** The document's title, taken from the report's first heading. */
    public String title() {
        return title;
    }

    /** The line of context printed under the title. */
    public String subtitle() {
        return subtitle;
    }

    /** The body, in reading order. */
    public List<Block> blocks() {
        return blocks;
    }

    /** The tables only, in reading order. Excel has nothing else to write. */
    public List<Table> tables() {
        return blocks.stream()
                .filter(Table.class::isInstance)
                .map(Table.class::cast)
                .toList();
    }

    /** True when there is something for a spreadsheet to hold. */
    public boolean hasTables() {
        return !tables().isEmpty();
    }

    /** Everything as plain text, used by the tests to check nothing was lost. */
    public String plainText() {
        StringBuilder sb = new StringBuilder(title).append('\n').append(subtitle).append('\n');
        for (Block block : blocks) {
            if (block instanceof Heading heading) {
                sb.append(heading.text()).append('\n');
            } else if (block instanceof Paragraph paragraph) {
                sb.append(paragraph.text()).append('\n');
            } else if (block instanceof Bullets bullets) {
                bullets.items().forEach(item -> sb.append(item).append('\n'));
            } else if (block instanceof Table table) {
                sb.append(String.join(" | ", table.header())).append('\n');
                for (List<String> row : table.rows()) {
                    sb.append(String.join(" | ", row)).append('\n');
                }
            }
        }
        return sb.toString();
    }
}
